/**
 * Writes migrations/0001_reference_data.sql from seed/grid-companies.json plus the static
 * zone and VAT tables below. Re-run after reviewing a new discovery result:
 *
 *   pnpm --filter @wattslot/db build:reference
 */
import { readFile, writeFile } from 'node:fs/promises';
import { z } from 'zod';

const SEED = new URL('../seed/grid-companies.json', import.meta.url);
const OUT = new URL('../migrations/0001_reference_data.sql', import.meta.url);

/** Danish zones get full prices; the others in DayAheadPrices are spot-only, in EUR. */
const ZONES = [
  { code: 'DK1', currency: 'DKK', timeZone: 'Europe/Copenhagen', fullPrice: true },
  { code: 'DK2', currency: 'DKK', timeZone: 'Europe/Copenhagen', fullPrice: true },
  { code: 'DE', currency: 'EUR', timeZone: 'Europe/Berlin', fullPrice: false },
  { code: 'NO2', currency: 'EUR', timeZone: 'Europe/Oslo', fullPrice: false },
  { code: 'SE3', currency: 'EUR', timeZone: 'Europe/Stockholm', fullPrice: false },
  { code: 'SE4', currency: 'EUR', timeZone: 'Europe/Stockholm', fullPrice: false },
];

/** Danish VAT has been 25% since 1 January 1992. */
const VAT = [
  { zone: 'DK1', validFrom: '1992-01-01', basisPoints: 2500 },
  { zone: 'DK2', validFrom: '1992-01-01', basisPoints: 2500 },
];

const seed = z.object({
  referenceTime: z.string(),
  source: z.string(),
  gridCompanies: z.array(
    z.object({
      gln: z.string().regex(/^\d{13}$/),
      name: z.string(),
      zone: z.enum(['DK1', 'DK2']),
      meteringPoints: z.number().int().nonnegative(),
      support: z.enum(['supported', 'unsupported']),
      supportNote: z.string().nullable(),
      components: z.array(z.object({ code: z.string(), role: z.enum(['tariff', 'discount']) })),
    }),
  ),
});

const str = (value: string | null) =>
  value === null ? 'NULL' : `'${value.replaceAll("'", "''")}'`;

const data = seed.parse(JSON.parse(await readFile(SEED, 'utf8')));
for (const c of data.gridCompanies) {
  const tariffs = c.components.filter((x) => x.role === 'tariff').length;
  if (c.support === 'supported' && tariffs === 0)
    throw new Error(`${c.name}: supported without a tariff`);
}

const statements = [
  `INSERT INTO price_zones (code, currency, time_zone, full_price) VALUES\n${ZONES.map(
    (z) => `  (${str(z.code)}, ${str(z.currency)}, ${str(z.timeZone)}, ${z.fullPrice ? 1 : 0})`,
  ).join(',\n')};`,
  `INSERT INTO vat_rates (zone, valid_from, valid_to, basis_points) VALUES\n${VAT.map(
    (v) => `  (${str(v.zone)}, ${str(v.validFrom)}, NULL, ${v.basisPoints})`,
  ).join(',\n')};`,
  `INSERT INTO grid_companies (gln, name, zone, metering_points, support, support_note) VALUES\n${data.gridCompanies
    .map(
      (c) =>
        `  (${str(c.gln)}, ${str(c.name.replace(/\s+/g, ' ').trim())}, ${str(c.zone)}, ${c.meteringPoints}, ${str(c.support)}, ${str(c.supportNote)})`,
    )
    .join(',\n')};`,
  `INSERT INTO tariff_mappings (gln, customer_type, charge_code, role) VALUES\n${data.gridCompanies
    .flatMap((c) =>
      c.components.map((x) => `  (${str(c.gln)}, 'C', ${str(x.code)}, ${str(x.role)})`),
    )
    .join(',\n')};`,
];

const header = `-- Reference data: price zones, VAT and Danish grid companies with their household tariffs.
-- Generated by scripts/build-reference-migration.ts from seed/grid-companies.json
-- (tariffs as of ${data.referenceTime}). Do not edit by hand.
-- Source: ${data.source}
`;
await writeFile(OUT, `${header}\n${statements.join('\n--> statement-breakpoint\n')}\n`);
console.log(`wrote ${data.gridCompanies.length} grid companies to ${OUT.pathname}`);
